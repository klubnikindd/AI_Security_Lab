import os
import json
import time
import logging

import httpx
from fastapi import FastAPI, Request, Response
from fastapi.responses import JSONResponse, StreamingResponse
from prometheus_client import (
    Counter,
    Gauge,
    Histogram,
    generate_latest,
    CONTENT_TYPE_LATEST,
)

# --- Конфигурация ---
OLLAMA_URL = os.getenv("OLLAMA_URL", "http://ollama:11434")

app = FastAPI(title="Ollama Metrics Exporter")

# --- Метрики Prometheus ---
OLLAMA_REQUESTS = Counter(
    "ollama_requests_total",
    "Total requests to Ollama",
    ["model", "endpoint"],
)
OLLAMA_TOKENS_GENERATED = Counter(
    "ollama_generated_tokens_total",
    "Total tokens generated by Ollama",
    ["model"],
)
OLLAMA_TOKENS_PROMPT = Counter(
    "ollama_prompt_tokens_total",
    "Total prompt tokens processed by Ollama",
    ["model"],
)
OLLAMA_TOKENS_PER_SECOND = Gauge(
    "ollama_tokens_per_second",
    "Last generation speed (tokens/sec)",
    ["model"],
)
OLLAMA_DURATION = Histogram(
    "ollama_request_duration_seconds",
    "Request duration",
    ["model", "endpoint"],
    buckets=[0.5, 1, 2, 5, 10, 30, 60, 120],
)
OLLAMA_ERRORS = Counter(
    "ollama_errors_total",
    "Errors from Ollama",
    ["model"],
)

# --- Таймауты ---
GENERATE_TIMEOUT = httpx.Timeout(connect=5.0, read=300.0, write=30.0, pool=5.0)
PASSTHROUGH_TIMEOUT = httpx.Timeout(connect=5.0, read=60.0, write=30.0, pool=5.0)


def _record_metrics(model: str, data: dict, endpoint: str, duration: float) -> None:
    """Извлекает метрики из ответа Ollama и обновляет счётчики."""
    OLLAMA_REQUESTS.labels(model=model, endpoint=endpoint).inc()
    OLLAMA_DURATION.labels(model=model, endpoint=endpoint).observe(duration)

    eval_count = data.get("eval_count", 0) or 0
    eval_duration_ns = data.get("eval_duration", 0) or 0
    prompt_eval_count = data.get("prompt_eval_count", 0) or 0

    if eval_count:
        OLLAMA_TOKENS_GENERATED.labels(model=model).inc(eval_count)
    if prompt_eval_count:
        OLLAMA_TOKENS_PROMPT.labels(model=model).inc(prompt_eval_count)
    if eval_count and eval_duration_ns:
        tps = eval_count / (eval_duration_ns / 1e9)
        OLLAMA_TOKENS_PER_SECOND.labels(model=model).set(tps)


@app.get("/metrics")
def metrics() -> Response:
    """Prometheus scrape endpoint."""
    return Response(content=generate_latest(), media_type=CONTENT_TYPE_LATEST)


@app.get("/health")
def health() -> dict:
    return {"status": "ok", "ollama_url": OLLAMA_URL}


@app.post("/api/generate")
async def proxy_generate(request: Request):
    """Прокси к /api/generate с записью метрик."""
    body = await request.json()
    model = body.get("model", "unknown")
    stream = body.get("stream", False)
    endpoint = "/api/generate"

    # --- Не-стриминговый режим ---
    if not stream:
        start = time.time()
        try:
            async with httpx.AsyncClient(timeout=GENERATE_TIMEOUT) as client:
                resp = await client.post(f"{OLLAMA_URL}/api/generate", json=body)
                resp.raise_for_status()
                data = resp.json()
        except httpx.HTTPError as e:
            OLLAMA_ERRORS.labels(model=model).inc()
            logging.warning(f"[exporter] Ollama error for model={model}: {e}")
            return JSONResponse(
                status_code=502,
                content={"error": f"Ollama error: {e}"},
            )

        duration = time.time() - start
        _record_metrics(model, data, endpoint, duration)
        return JSONResponse(content=data)

    # --- Стриминговый режим ---
    async def stream_generator():
        start = time.time()
        last_data: dict = {}
        try:
            async with httpx.AsyncClient(timeout=GENERATE_TIMEOUT) as client:
                async with client.stream(
                    "POST", f"{OLLAMA_URL}/api/generate", json=body
                ) as r:
                    async for chunk in r.aiter_raw():
                        yield chunk
                        # Пытаемся распарсить финальный чанк с метриками
                        try:
                            parsed = json.loads(chunk)
                            if parsed.get("done"):
                                last_data = parsed
                        except json.JSONDecodeError:
                            # Чанк может быть неполным JSON — это нормально
                            continue
        except httpx.HTTPError as e:
            OLLAMA_ERRORS.labels(model=model).inc()
            logging.warning(f"[exporter] Streaming error for model={model}: {e}")
            yield json.dumps({"error": str(e)}).encode()
            return
        finally:
            duration = time.time() - start
            _record_metrics(model, last_data, endpoint, duration)

    return StreamingResponse(stream_generator(), media_type="application/x-ndjson")


@app.api_route("/{path:path}", methods=["GET", "POST", "DELETE", "PUT"])
async def passthrough(path: str, request: Request):
    """Прозрачный прокси для остальных эндпоинтов Ollama (без метрик)."""
    async with httpx.AsyncClient(timeout=PASSTHROUGH_TIMEOUT) as client:
        body = await request.body()
        headers = {
            k: v
            for k, v in request.headers.items()
            if k.lower() not in ("host", "content-length")
        }
        resp = await client.request(
            method=request.method,
            url=f"{OLLAMA_URL}/{path}",
            content=body,
            headers=headers,
        )
    return Response(
        content=resp.content,
        status_code=resp.status_code,
        media_type=resp.headers.get("content-type"),
    )